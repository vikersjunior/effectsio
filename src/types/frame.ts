export function isImageSource(source: unknown): source is ImageSource {
  return (
    typeof source === "object" &&
    source !== null &&
    (source as ImageSource).type === "image" &&
    typeof (source as ImageSource).assetId === "string"
  );
}

export function isProceduralSource(source: unknown): source is ProceduralSource {
  return (
    typeof source === "object" &&
    source !== null &&
    (source as ProceduralSource).type === "procedural" &&
    typeof (source as ProceduralSource).kind === "string" &&
    typeof (source as ProceduralSource).parameters === "object"
  );
}

export function isImageLayer(layer: Layer): layer is ImageLayer {
  return layer.type === "image" || (Boolean(layer.source) && isImageSource(layer.source));
}

export function isGenerativeLayer(layer: Layer): layer is GenerativeLayer {
  return layer.type === "generative";
}

