/**
 * Creates a canonical Layer in the Unified Composition Model.
 *
 * Every Layer requires exactly one canonical LayerSource (`source`), which is the authoritative
 * pixel generator.
 *
 * Migration boundary note: This factory intentionally populates explicitly deprecated compatibility
 * fields (type, assetId) because un-migrated downstream consumers (Phase 2 compositor, Phase 3 studio state,
 * Phase 4 UI) still require them during Phase 1. These fields are migration adapters only, not canonical architecture,
 * and `layer.source` remains the sole canonical source of truth.
 */
export function createLayer(params: {
  id?: string;
  name: string;
  source: LayerSource;
  visible?: boolean;
  opacity?: number;
  blendMode?: BlendMode;
  effectStack?: EffectStack;
  transform?: Partial<LayerTransform>;
  fit?: "contain" | "cover";
  locked?: boolean;
  groupId?: string | null;
}): Layer {
  const now = Date.now();
  const baseId =
    params.id ||
    (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
      ? crypto.randomUUID()
      : `layer-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`);

  const transform: LayerTransform = {
    x: params.transform && Number.isFinite(params.transform.x) ? params.transform.x! : DEFAULT_LAYER_TRANSFORM.x,
    y: params.transform && Number.isFinite(params.transform.y) ? params.transform.y! : DEFAULT_LAYER_TRANSFORM.y,
    scaleX: params.transform && Number.isFinite(params.transform.scaleX) ? Math.max(0.05, Math.min(20, params.transform.scaleX!)) : DEFAULT_LAYER_TRANSFORM.scaleX,
    scaleY: params.transform && Number.isFinite(params.transform.scaleY) ? Math.max(0.05, Math.min(20, params.transform.scaleY!)) : DEFAULT_LAYER_TRANSFORM.scaleY,
    rotation: params.transform && Number.isFinite(params.transform.rotation) ? params.transform.rotation! : DEFAULT_LAYER_TRANSFORM.rotation,
  };

  const layer: Layer = {
    id: baseId,
    name: params.name,
    visible: params.visible ?? true,
    opacity: typeof params.opacity === "number" ? Math.max(0, Math.min(1, params.opacity)) : 1.0,
    blendMode: params.blendMode ?? "normal",
    effectStack: params.effectStack ? [...params.effectStack] : [],
    locked: params.locked ?? false,
    source: params.source,
    fit: params.fit || "contain",
    transform,
    createdAt: now,
    updatedAt: now,
  };

  // Populate legacy compatibility fields for un-migrated consumers
  if (params.source.type === "image") {
    layer.type = "image";
    layer.assetId = params.source.assetId;
  } else if (params.source.type === "procedural") {
    layer.type = "procedural";
  }

  return layer;
}

