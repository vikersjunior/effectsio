/**
 * Normalizes an individual Layer into one or more Universal Layers.
 *
 * In the Unified Composition Model:
 * 1. An ImageLayer (or legacy image record) maps to a single Layer with ImageSource(assetId).
 * 2. A legacy GenerativeLayer (with stackable backgrounds) expands into individual
 *    Layers with ProceduralSource, preserving visual order, parameters, blend modes,
 *    opacity, and visibility.
 * 3. An already-canonical Layer (with ImageSource or ProceduralSource)
 *    is returned cleanly without mutation or re-migration (idempotent).
 */
export function normalizeLayerToUniversal(layer: Layer | Record<string, unknown>): Layer[] {
  if (!layer || typeof layer !== "object") return [];

  const candidate = layer as Record<string, unknown>;
  const now = Date.now();

  // Case 1: Already canonical Layer with valid LayerSource
  // If the layer already has a canonical LayerSource (and does not contain an unexpanded multi-item legacy background stack)
  const hasMultipleLegacyBackgrounds =
    Array.isArray(candidate.backgrounds) && candidate.backgrounds.length > 1;

  if (candidate.source && !hasMultipleLegacyBackgrounds) {
    if (isImageSource(candidate.source) || (candidate.source as Record<string, unknown>).type === "image") {
      const rawSource = candidate.source as ImageSource;
      const assetId = (rawSource?.assetId || candidate.assetId || "") as string;
      const source: ImageSource = {
        type: "image",
        assetId,
      };

      const rawTransform = candidate.transform as Partial<LayerTransform> | undefined;
      const transform: LayerTransform = {
        x: rawTransform && Number.isFinite(rawTransform.x) ? rawTransform.x! : DEFAULT_LAYER_TRANSFORM.x,
        y: rawTransform && Number.isFinite(rawTransform.y) ? rawTransform.y! : DEFAULT_LAYER_TRANSFORM.y,
        scaleX: rawTransform && Number.isFinite(rawTransform.scaleX) ? Math.max(0.05, Math.min(20, rawTransform.scaleX!)) : DEFAULT_LAYER_TRANSFORM.scaleX,
        scaleY: rawTransform && Number.isFinite(rawTransform.scaleY) ? Math.max(0.05, Math.min(20, rawTransform.scaleY!)) : DEFAULT_LAYER_TRANSFORM.scaleY,
        rotation: rawTransform && Number.isFinite(rawTransform.rotation) ? rawTransform.rotation! : DEFAULT_LAYER_TRANSFORM.rotation,
      };

      const imageLayer: ImageLayer = {
        id: (candidate.id as string) || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `img-${now}`),
        name: (candidate.name as string) || "Image Layer",
        visible: candidate.visible !== false,
        opacity: typeof candidate.opacity === "number" ? Math.max(0, Math.min(1, candidate.opacity as number)) : 1.0,
        blendMode: (candidate.blendMode as BlendMode) || "normal",
        effectStack: Array.isArray(candidate.effectStack) ? ([...candidate.effectStack] as EffectStack) : [],
        locked: Boolean(candidate.locked),
        type: "image",
        assetId,
        source,
        fit: (candidate.fit as "contain" | "cover") || "contain",
        transform,
        createdAt: (candidate.createdAt as number) || now,
        updatedAt: (candidate.updatedAt as number) || now,
      };

      return [imageLayer];
    }

    if (isProceduralSource(candidate.source) || (candidate.source as Record<string, unknown>).type === "procedural") {
      const procSource = candidate.source as ProceduralSource;
      const rawTransform = candidate.transform as Partial<LayerTransform> | undefined;
      const transform: LayerTransform = {
        x: rawTransform && Number.isFinite(rawTransform.x) ? rawTransform.x! : DEFAULT_LAYER_TRANSFORM.x,
        y: rawTransform && Number.isFinite(rawTransform.y) ? rawTransform.y! : DEFAULT_LAYER_TRANSFORM.y,
        scaleX: rawTransform && Number.isFinite(rawTransform.scaleX) ? Math.max(0.05, Math.min(20, rawTransform.scaleX!)) : DEFAULT_LAYER_TRANSFORM.scaleX,
        scaleY: rawTransform && Number.isFinite(rawTransform.scaleY) ? Math.max(0.05, Math.min(20, rawTransform.scaleY!)) : DEFAULT_LAYER_TRANSFORM.scaleY,
        rotation: rawTransform && Number.isFinite(rawTransform.rotation) ? rawTransform.rotation! : DEFAULT_LAYER_TRANSFORM.rotation,
      };

      const procLayer: Layer = {
        id: (candidate.id as string) || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `proc-${now}`),
        name: (candidate.name as string) || (candidate.name === "Background" ? "Background" : `${procSource.kind.charAt(0).toUpperCase() + procSource.kind.slice(1)} Layer`),
        visible: candidate.visible !== false,
        opacity: typeof candidate.opacity === "number" ? Math.max(0, Math.min(1, candidate.opacity as number)) : 1.0,
        blendMode: (candidate.blendMode as BlendMode) || "normal",
        effectStack: Array.isArray(candidate.effectStack) ? ([...candidate.effectStack] as EffectStack) : [],
        locked: Boolean(candidate.locked),
        type: (candidate.type as "procedural" | "generative") || "procedural",
        source: {
          type: "procedural",
          kind: procSource.kind,
          parameters: { ...procSource.parameters },
          seed: procSource.seed,
        },
        fit: (candidate.fit as "contain" | "cover") || "contain",
        transform,
        createdAt: (candidate.createdAt as number) || now,
        updatedAt: (candidate.updatedAt as number) || now,
      };

      return [procLayer];
    }
  }

  // Case 2: Legacy GenerativeLayer (or any layer containing backgrounds stack)
  const isGenerative =
    candidate.type === "generative" ||
    Array.isArray(candidate.backgrounds) ||
    Boolean(candidate.backgroundConfig);

  if (isGenerative) {
    let bgItems: BackgroundItem[] = [];
    if (Array.isArray(candidate.backgrounds) && candidate.backgrounds.length > 0) {
      bgItems = candidate.backgrounds as BackgroundItem[];
    } else if (Array.isArray(candidate.sublayers) && candidate.sublayers.length > 0) {
      bgItems = candidate.sublayers as BackgroundItem[];
    } else if (candidate.backgroundConfig) {
      bgItems = normalizeLegacyBackgroundToBackgrounds(candidate.backgroundConfig as BackgroundState);
    }

    // If no background items were found, synthesize a default solid background preserving candidate.id and transparent visibility
    if (bgItems.length === 0) {
      const bgConfig = candidate.backgroundConfig as Partial<BackgroundState> | undefined;
      const isExplicitlyVisible = candidate.visible !== false && Boolean(bgConfig && bgConfig.visible !== false);
      bgItems = [
        {
          id: (candidate.id as string) || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `bg-${Date.now()}`),
          type: "solid",
          enabled: isExplicitlyVisible,
          opacity: typeof candidate.opacity === "number" ? (candidate.opacity as number) : 1.0,
          blendMode: (candidate.blendMode as BlendMode) || "normal",
          parameters: { color: "#000000" },
        },
      ];
    }

    const effectStack = Array.isArray(candidate.effectStack) ? (candidate.effectStack as EffectStack) : [];
    const layerLocked = Boolean(candidate.locked);

    return bgItems.map((item, index) => {
      const proceduralSource: ProceduralSource = {
        type: "procedural",
        kind: item.type,
        parameters: item.parameters ? { ...item.parameters } : {},
        seed: item.seed,
      };

      const layerId = item.id || (index === 0 && candidate.id ? (candidate.id as string) : (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `bg-${now}-${index}`));

      const procLayer: Layer = {
        id: layerId,
        name: item.name || `${item.type.charAt(0).toUpperCase() + item.type.slice(1)} Background`,
        visible: item.enabled ?? true,
        opacity: typeof item.opacity === "number" ? Math.max(0, Math.min(1, item.opacity)) : 1.0,
        blendMode: item.blendMode || "normal",
        // The top procedural layer inherits any effectStack on the legacy GenerativeLayer
        effectStack: index === bgItems.length - 1 ? [...effectStack] : [],
        locked: index === 0 ? layerLocked : false,
        type: "procedural",
        source: proceduralSource,
        transform: { ...DEFAULT_LAYER_TRANSFORM },
        createdAt: (candidate.createdAt as number) || now,
        updatedAt: (candidate.updatedAt as number) || now,
      };

      return procLayer;
    });
  }

  // Case 3: Legacy Image Layer (without source)
  const isImage =
    candidate.type === "image" ||
    typeof candidate.assetId === "string";

  if (isImage) {
    const assetId = (candidate.assetId || "") as string;
    const source: ImageSource = {
      type: "image",
      assetId,
    };

    const rawTransform = candidate.transform as Partial<LayerTransform> | undefined;
    const transform: LayerTransform = {
      x: rawTransform && Number.isFinite(rawTransform.x) ? rawTransform.x! : DEFAULT_LAYER_TRANSFORM.x,
      y: rawTransform && Number.isFinite(rawTransform.y) ? rawTransform.y! : DEFAULT_LAYER_TRANSFORM.y,
      scaleX: rawTransform && Number.isFinite(rawTransform.scaleX) ? Math.max(0.05, Math.min(20, rawTransform.scaleX!)) : DEFAULT_LAYER_TRANSFORM.scaleX,
      scaleY: rawTransform && Number.isFinite(rawTransform.scaleY) ? Math.max(0.05, Math.min(20, rawTransform.scaleY!)) : DEFAULT_LAYER_TRANSFORM.scaleY,
      rotation: rawTransform && Number.isFinite(rawTransform.rotation) ? rawTransform.rotation! : DEFAULT_LAYER_TRANSFORM.rotation,
    };

    const imageLayer: ImageLayer = {
      id: (candidate.id as string) || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `img-${now}`),
      name: (candidate.name as string) || "Image Layer",
      visible: candidate.visible !== false,
      opacity: typeof candidate.opacity === "number" ? Math.max(0, Math.min(1, candidate.opacity as number)) : 1.0,
      blendMode: (candidate.blendMode as BlendMode) || "normal",
      effectStack: Array.isArray(candidate.effectStack) ? ([...candidate.effectStack] as EffectStack) : [],
      locked: Boolean(candidate.locked),
      type: "image",
      assetId,
      source,
      fit: (candidate.fit as "contain" | "cover") || "contain",
      transform,
      createdAt: (candidate.createdAt as number) || now,
      updatedAt: (candidate.updatedAt as number) || now,
    };

    return [imageLayer];
  }

  // Fallback: return candidate as-is if unrecognized
  return [candidate as unknown as Layer];
}

/**
 * Flattens all visual Layers from root composition items in bottom-to-top order.
 */
export function flattenItemsToLayers(items: (Layer | Group)[]): Layer[] {
  const result: Layer[] = [];
  for (const item of items) {
    if (isLayer(item)) {
      result.push(item);
    } else if (isGroup(item)) {
      for (const child of item.children) {
        result.push(child);
      }
    }
  }
  return result;
}

/**
 * @deprecated Legacy migration adapter. Canonical runtime preserves empty item lists without manufacturing content.
 */
export function normalizeBackdrop(items: (Layer | Group)[]): (Layer | Group)[] {
  return items;
}

/**
 * Normalizes a complete Frame into the Unified Composition Model (Canonical Model B).
 *
 * Guaranteed Invariants:
 * 1. Frame.items is the sole composition stack (Layer | Group)[].
 * 2. Frame.items represents the entire composition stack in bottom-to-top order. An intentionally empty composition (items = []) is fully valid and preserved.
 * 3. Group membership is strictly physical containment (Group.children: Layer[]).
 * 4. Nested groups are dissolved inline and their visibility/lock state materialized onto children.
 * 5. Empty groups are auto-pruned.
 * 6. activeLayerId is preserved or safely recovered.
 * 7. Idempotency: normalize(normalize(x)) produces an identical structure.
 */
export function normalizeFrameToUniversalModel(rawFrame: unknown): Frame {
  if (!rawFrame || typeof rawFrame !== "object") {
    return createDefaultFrame();
  }

  const raw = rawFrame as Record<string, unknown>;
  const now = Date.now();

  let items: (Layer | Group)[] = [];

  // Case 1: Raw input already has `items`
  if (Array.isArray(raw.items)) {
    for (const rawItem of raw.items) {
      if (!rawItem || typeof rawItem !== "object") continue;

      if (Array.isArray((rawItem as any).children)) {
        // Group container
        const rawGroup = rawItem as Record<string, unknown>;
        const normalizedChildren: Layer[] = [];

        for (const child of (rawGroup.children as any[])) {
          if (!child || typeof child !== "object") continue;
          if (Array.isArray(child.children)) {
            // Nested Group: dissolve inline and materialize state onto children
            const nestedGroup = child as Record<string, unknown>;
            const nestedVisible = nestedGroup.visible !== false;
            const nestedLocked = Boolean(nestedGroup.locked);
            for (const grandChild of (nestedGroup.children as any[])) {
              const normalizedGrandChildren = normalizeLayerToUniversal(grandChild);
              for (const gc of normalizedGrandChildren) {
                normalizedChildren.push({
                  ...gc,
                  visible: nestedVisible && gc.visible !== false,
                  locked: Boolean(nestedLocked || gc.locked),
                });
              }
            }
          } else {
            const normalized = normalizeLayerToUniversal(child);
            normalizedChildren.push(...normalized);
          }
        }

        // Only keep group if it has at least 1 child (auto-prune empty groups)
        if (normalizedChildren.length > 0) {
          const rawGroupTransform = rawGroup.transform as Partial<LayerTransform> | undefined;
          const groupTransform: LayerTransform = {
            x: rawGroupTransform && Number.isFinite(rawGroupTransform.x) ? rawGroupTransform.x! : DEFAULT_LAYER_TRANSFORM.x,
            y: rawGroupTransform && Number.isFinite(rawGroupTransform.y) ? rawGroupTransform.y! : DEFAULT_LAYER_TRANSFORM.y,
            scaleX: rawGroupTransform && Number.isFinite(rawGroupTransform.scaleX) ? Math.max(0.05, Math.min(20, rawGroupTransform.scaleX!)) : DEFAULT_LAYER_TRANSFORM.scaleX,
            scaleY: rawGroupTransform && Number.isFinite(rawGroupTransform.scaleY) ? Math.max(0.05, Math.min(20, rawGroupTransform.scaleY!)) : DEFAULT_LAYER_TRANSFORM.scaleY,
            rotation: rawGroupTransform && Number.isFinite(rawGroupTransform.rotation) ? rawGroupTransform.rotation! : DEFAULT_LAYER_TRANSFORM.rotation,
          };

          items.push({
            id: String(rawGroup.id || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? `group-${crypto.randomUUID()}` : `group-${now}`)),
            name: String(rawGroup.name || "Group"),
            children: normalizedChildren,
            visible: rawGroup.visible !== false,
            locked: Boolean(rawGroup.locked),
            collapsed: Boolean(rawGroup.collapsed),
            opacity: typeof rawGroup.opacity === "number" && !isNaN(rawGroup.opacity) ? Math.max(0, Math.min(1, rawGroup.opacity)) : 1.0,
            blendMode: (rawGroup.blendMode as BlendMode) || "normal",
            effectStack: Array.isArray(rawGroup.effectStack) ? (rawGroup.effectStack as EffectStack) : [],
            transform: groupTransform,
            createdAt: Number(rawGroup.createdAt) || now,
            updatedAt: Number(rawGroup.updatedAt) || now,
          });
        }
      } else {
        // Layer
        const normalized = normalizeLayerToUniversal(rawItem);
        items.push(...normalized);
      }
    }
  } else if (Array.isArray(raw.layers)) {
    // Case 2: Legacy Model A format with `layers` and optional `groups`
    const normalizedLayers = (raw.layers as any[]).flatMap((l) => normalizeLayerToUniversal(l));
    const legacyGroups = Array.isArray(raw.groups) ? (raw.groups as any[]) : [];
    const groupedLayerIdSet = new Set<string>();
    const groupMap = new Map<string, { group: any; children: Layer[]; minIndex: number }>();

    for (const g of legacyGroups) {
      if (!g || !Array.isArray(g.layerIds)) continue;
      const childLayers: Layer[] = [];
      let minIndex = Number.MAX_SAFE_INTEGER;
      for (let i = 0; i < normalizedLayers.length; i++) {
        const layer = normalizedLayers[i];
        if (g.layerIds.includes(layer.id) || (layer as any).groupId === g.id) {
          childLayers.push(layer);
          groupedLayerIdSet.add(layer.id);
          if (i < minIndex) minIndex = i;
        }
      }
      if (childLayers.length > 0) {
        groupMap.set(g.id, { group: g, children: childLayers, minIndex });
      }
    }

    const placedGroupIds = new Set<string>();
    for (let i = 0; i < normalizedLayers.length; i++) {
      const layer = normalizedLayers[i];
      for (const [gid, gData] of groupMap.entries()) {
        if (!placedGroupIds.has(gid) && gData.minIndex === i) {
          items.push({
            id: String(gData.group.id || `group-${now}`),
            name: String(gData.group.name || "Group"),
            children: gData.children,
            visible: gData.group.visible !== false,
            locked: Boolean(gData.group.locked),
            collapsed: Boolean(gData.group.collapsed),
            opacity: typeof gData.group.opacity === "number" ? Math.max(0, Math.min(1, gData.group.opacity)) : 1.0,
            blendMode: (gData.group.blendMode as BlendMode) || "normal",
            effectStack: Array.isArray(gData.group.effectStack) ? (gData.group.effectStack as EffectStack) : [],
            transform: gData.group.transform ? { ...DEFAULT_LAYER_TRANSFORM, ...gData.group.transform } : { ...DEFAULT_LAYER_TRANSFORM },
            createdAt: Number(gData.group.createdAt) || now,
            updatedAt: Number(gData.group.updatedAt) || now,
          });
          placedGroupIds.add(gid);
        }
      }

      if (!groupedLayerIdSet.has(layer.id)) {
        items.push(layer);
      }
    }

    for (const [gid, gData] of groupMap.entries()) {
      if (!placedGroupIds.has(gid)) {
        items.push({
          id: String(gData.group.id || `group-${now}`),
          name: String(gData.group.name || "Group"),
          children: gData.children,
          visible: gData.group.visible !== false,
          locked: Boolean(gData.group.locked),
          collapsed: Boolean(gData.group.collapsed),
          opacity: typeof gData.group.opacity === "number" ? Math.max(0, Math.min(1, gData.group.opacity)) : 1.0,
          blendMode: (gData.group.blendMode as BlendMode) || "normal",
          effectStack: Array.isArray(gData.group.effectStack) ? (gData.group.effectStack as EffectStack) : [],
          transform: gData.group.transform ? { ...DEFAULT_LAYER_TRANSFORM, ...gData.group.transform } : { ...DEFAULT_LAYER_TRANSFORM },
          createdAt: Number(gData.group.createdAt) || now,
          updatedAt: Number(gData.group.updatedAt) || now,
        });
        placedGroupIds.add(gid);
      }
    }
  }

  // Recover or preserve activeLayerId (supporting both Layer and Group IDs)
  let activeLayerId = typeof raw.activeLayerId === "string" ? raw.activeLayerId : null;
  const itemExists = items.some((item) => {
    if (item.id === activeLayerId) return true;
    if (isGroup(item)) {
      return item.children.some((c) => c.id === activeLayerId);
    }
    return false;
  });

  if (!itemExists) {
    const allFlattenedLayers = flattenItemsToLayers(items);
    if (allFlattenedLayers.length > 0) {
      activeLayerId = allFlattenedLayers[allFlattenedLayers.length - 1].id;
    } else if (items.length > 0) {
      activeLayerId = items[items.length - 1].id;
    } else {
      activeLayerId = null;
    }
  }

  const frameDimensions = (raw.dimensions as any) || DEFAULT_FRAME_DIMENSIONS;

  return {
    id: String(raw.id || (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function" ? crypto.randomUUID() : `frame-${now}`)),
    name: String(raw.name || "Frame 1"),
    dimensions: {
      width: Number(frameDimensions.width) || 1080,
      height: Number(frameDimensions.height) || 1080,
      presetId: frameDimensions.presetId ?? null,
    },
    items,
    activeLayerId: activeLayerId ?? (items[0] && isLayer(items[0]) ? items[0].id : null),
    createdAt: Number(raw.createdAt) || now,
    updatedAt: Number(raw.updatedAt) || now,
  };
}
