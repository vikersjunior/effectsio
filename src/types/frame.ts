/**
 * Synthesizes a canonical backdrop Layer for a Frame.
 *
 * In the Unified Composition Model:
 * The backdrop is an ordinary canonical Layer whose pixels originate from a ProceduralSource,
 * fulfilling the background visual role based on its position and creative intent (no special
 * background type is required).
 *
 * Architectural flow:
 * Background role -> ordinary Layer -> ProceduralSource
 * (NOT: GenerativeLayer -> BackgroundStack)
 *
 * Legacy background/generative fields (type: "generative", backgrounds, sublayers, backgroundMode,
 * backgroundConfig) are populated strictly as temporary compatibility data for un-migrated Phase 2-4 consumers.
 * They are not the canonical representation of the backdrop and are scheduled for removal during downstream migration.
 *
 * NOTE: The default `locked: true` is merely a UI convenience default for newly synthesized default frames,
 * NOT a structural protection. The procedural backdrop is an ordinary Layer that can be unlocked, edited,
 * reordered, and deleted.
 */
export function createDefaultBackdropLayer(backgroundConfig?: BackgroundState): Layer {
  const now = Date.now();
  const hasExplicitConfig = Boolean(backgroundConfig);
  const config = backgroundConfig ? { ...backgroundConfig } : { ...DEFAULT_BACKGROUND_STATE };
  const backgrounds = normalizeLegacyBackgroundToBackgrounds(config);
  const primaryBg = backgrounds[0];
  const source: ProceduralSource = primaryBg
    ? {
        type: "procedural",
        kind: primaryBg.type,
        parameters: { ...primaryBg.parameters },
        seed: primaryBg.seed,
      }
    : {
        type: "procedural",
        kind: "solid",
        parameters: { color: "#000000" },
      };

  const backdropId =
    typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
      ? crypto.randomUUID()
      : `bg-${Date.now()}`;
  if (primaryBg) {
    primaryBg.id = backdropId;
  }

  return {
    id: backdropId,
    name: "Background",
    visible: hasExplicitConfig ? (config.visible ?? true) : false,
    opacity: 1.0,
    blendMode: "normal",
    effectStack: [],
    locked: true,
    source,
    transform: { ...DEFAULT_LAYER_TRANSFORM },
    fit: "contain",
    type: "procedural",
    createdAt: now,
    updatedAt: now,
  };
}

/** @deprecated Legacy migration adapter for un-migrated Phase 2-4 consumers. Use createDefaultBackdropLayer instead. */
export function createDefaultGenerativeLayer(backgroundConfig?: BackgroundState): GenerativeLayer {
  const backdrop = createDefaultBackdropLayer(backgroundConfig);
  delete (backdrop as any).source;
  return backdrop as GenerativeLayer;
}

