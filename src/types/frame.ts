/**
 * ImageSource describes visual content generated from an immutable Asset bitmap.
 * Universal rule: If it creates pixels -> Source.
 */
export interface ImageSource {
  type: "image";
  assetId: string; // References immutable source Asset in assets store
}

/**
 * ProceduralSource describes algorithmic visual content generated by procedural shaders.
 * Universal rule: If it creates pixels -> Source.
 * Supported kinds: "solid" | "linear-gradient" | "radial-gradient" | "dots" | "grid".
 */
export interface ProceduralSource {
  type: "procedural";
  kind: BackgroundItemType;
  parameters: Record<string, unknown>;
  seed?: number;
}

/**
 * LayerSource describes what generates a Layer's visual content.
 * Universal rule: If it creates pixels -> Source.
 */
export type LayerSource = ImageSource | ProceduralSource;

